val apiBaseUrl: String = (findProperty("permutados.apiBaseUrl") as String?) ?: "https://api.permutados.example/"

// Release signing is read from keystore.properties (never committed). Without it, assembleRelease produces an
// unsigned APK that must be signed by the owner (see README "APK de release").
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

